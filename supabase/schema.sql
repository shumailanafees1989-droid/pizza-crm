create table if not exists public.customers (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  phone       text not null,
  email       text,
  address     text,
  notes       text,
  created_at  timestamptz not null default now()
);

create table if not exists public.menu_items (
  id           uuid primary key default gen_random_uuid(),
  name         text not null,
  description  text,
  category     text not null default 'pizza' check (category in ('pizza','sides','desserts','drinks')),
  emoji        text,
  -- {"small":9.5,"medium":13,"large":16.5} for pizzas, {"regular":5.5} for everything else
  prices       jsonb not null default '{}'::jsonb,
  ingredients  text[] not null default '{}',
  available    boolean not null default true,
  created_at   timestamptz not null default now()
);

create table if not exists public.staff (
  id           uuid primary key default gen_random_uuid(),
  name         text not null,
  role         text not null,
  phone        text,
  email        text,
  shift        text,
  hourly_rate  numeric(8,2) default 0,
  status       text not null default 'active' check (status in ('active','on_leave','inactive')),
  hired_on     date,
  created_at   timestamptz not null default now()
);

create table if not exists public.tasks (
  id           uuid primary key default gen_random_uuid(),
  title        text not null,
  description  text,
  staff_id     uuid references public.staff(id) on delete set null,
  priority     text not null default 'medium' check (priority in ('low','medium','high')),
  status       text not null default 'todo' check (status in ('todo','in_progress','done')),
  due_date     date,
  created_at   timestamptz not null default now()
);

create table if not exists public.inventory (
  id             uuid primary key default gen_random_uuid(),
  name           text not null,
  category       text,
  unit           text not null default 'pcs',
  quantity       numeric(10,2) not null default 0,
  reorder_level  numeric(10,2) not null default 0,
  cost_per_unit  numeric(10,2) default 0,
  supplier       text,
  updated_at     timestamptz not null default now(),
  created_at     timestamptz not null default now()
);

create table if not exists public.orders (
  id               uuid primary key default gen_random_uuid(),
  order_no         bigint generated by default as identity (start with 1001) unique,
  customer_id      uuid references public.customers(id) on delete set null,
  customer_name    text,                       -- snapshot, used for guests / deleted customers
  order_type       text not null default 'delivery' check (order_type in ('delivery','pickup','dine-in')),
  address          text,
  -- [{"menu_item_id":"…","name":"Margherita","size":"large","qty":2,"unit_price":16.5}]
  items            jsonb not null default '[]'::jsonb,
  delivery_fee     numeric(8,2) not null default 0,
  total            numeric(10,2) not null default 0,
  payment_method   text not null default 'card' check (payment_method in ('card','cash','online')),
  payment_status   text not null default 'pending' check (payment_status in ('paid','pending','refunded')),
  delivery_status  text not null default 'pending'
                   check (delivery_status in ('pending','preparing','ready','out_for_delivery','delivered','cancelled')),
  notes            text,
  created_at       timestamptz not null default now()
);

create index if not exists orders_created_at_idx  on public.orders (created_at desc);
create index if not exists orders_customer_idx    on public.orders (customer_id);
create index if not exists orders_status_idx      on public.orders (delivery_status);
create index if not exists tasks_staff_idx        on public.tasks (staff_id);
create index if not exists customers_phone_idx    on public.customers (phone);

-- ----------------------------------------------------------------------------
-- Row Level Security: only signed-in users (your staff) can read / write.
-- Create users in Authentication → Users → Add user (and turn OFF public
-- sign-ups under Authentication → Providers → Email).
-- ----------------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['customers','menu_items','staff','tasks','inventory','orders'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "Authenticated full access" on public.%I', t);
    execute format(
      'create policy "Authenticated full access" on public.%I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;
